import type { CheckResult, Comparison } from '@tracegate/core';
import { ci, f, money, pct } from './util.js';

const sign = (x: number, d = 3) => (x >= 0 ? '+' : '') + f(x, d);
const icon = { fail: '❌', warn: '⚠️', info: 'ℹ️' } as const;

/** Markdown summary for a pull-request comment. */
export function renderMarkdown(res: CheckResult, title = 'Tracegate report'): string {
  const c = res.comparison;
  const L: string[] = [`## ${res.ok ? '✅' : '❌'} ${title}: ${res.ok ? 'passed' : 'failed'}`, ''];
  if (res.findings.length) {
    for (const x of res.findings) L.push(`- ${icon[x.level]} **${x.kind}**: ${x.message}`);
    L.push('');
  }
  if (c) L.push(...comparisonTables(c));
  L.push(
    '',
    '<sub>Generated by Tracegate. Intervals are 95% paired-bootstrap CIs over cases; p-values are two-sided. See docs/STATISTICS.md.</sub>',
  );
  return L.join('\n');
}

export function comparisonTables(c: Comparison): string[] {
  const L: string[] = [];
  L.push(
    `**${c.baseline.name}** (baseline) vs **${c.candidate.name}** (candidate): ${c.n_paired} paired cases, ${c.baseline.trials_per_case}/${c.candidate.trials_per_case} trials per case`,
    '',
  );
  L.push('| Metric | Baseline | Candidate | Diff (95% CI) | p | Verdict |', '|---|---|---|---|---|---|');
  const order = ['task_success', 'tool_accuracy', 'retrieval_recall', 'citation_accuracy', 'cost_usd', 'latency_ms', 'tokens', 'steps'];
  const ms = [...c.metrics].sort((a, b) => ((order.indexOf(a.name) + 99) % 99) - ((order.indexOf(b.name) + 99) % 99));
  for (const m of ms.slice(0, 12)) {
    const money_ = m.name === 'cost_usd';
    const fm = (x: number) => (money_ ? money(x) : f(x));
    L.push(
      `| ${m.name} | ${fm(m.baseline)} | ${fm(m.candidate)} | ${sign(m.diff.diff)} (${f(m.diff.lo)}, ${f(m.diff.hi)}) | ${f(m.diff.p)} | ${m.verdict.replace(/_/g, ' ')} |`,
    );
  }
  L.push(
    '',
    `Pass/fail changes (exact McNemar): ${c.pass_test.regressed} regressed, ${c.pass_test.improved} improved, p = ${f(c.pass_test.p)}.`,
  );
  const reg = c.changes.filter((x) => x.kind === 'regressed');
  const imp = c.changes.filter((x) => x.kind === 'improved');
  const flaky = c.changes.filter((x) => x.kind === 'flaky');
  if (reg.length)
    L.push(
      '',
      `**Regressed cases (${reg.length})**`,
      ...reg
        .slice(0, 10)
        .map(
          (x) =>
            `- \`${x.case_id}\` ${pct(x.baseline_pass_rate)} → ${pct(x.candidate_pass_rate)}${x.failures[0] ? `: ${x.failures[0].slice(0, 140)}` : ''}`,
        ),
    );
  if (imp.length)
    L.push(
      '',
      `**Improved cases (${imp.length})**: ${imp
        .slice(0, 10)
        .map((x) => `\`${x.case_id}\``)
        .join(', ')}`,
    );
  if (flaky.length)
    L.push(
      '',
      `**Flaky cases (${flaky.length})**: ${flaky
        .slice(0, 10)
        .map((x) => `\`${x.case_id}\``)
        .join(', ')}`,
    );
  const cq = c.cost_quality;
  L.push(
    '',
    `Cost vs quality: ${money(cq.baseline.cost)} → ${money(cq.candidate.cost)} per case, pass rate ${pct(cq.baseline.quality)} → ${pct(cq.candidate.quality)}.`,
  );
  for (const n of c.notes) L.push('', `> ${n}`);
  return L;
}
export { ci };
