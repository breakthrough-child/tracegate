// Converts OpsDesk eval results (https://github.com/breakthrough-child/OpsDesk) into Tracegate traces and a dataset.
//   node examples/opsdesk/import.mjs ../OpsDesk      (reads evals/results and evals/cases; makes no network calls)
// The output is committed, so the example runs without OpsDesk and without an API key.
// OpsDesk saves per-case outcomes (tools used, gated actions, escalation, reply, cost, latency), not raw model requests,
// so these traces can be scored and compared but not strictly replayed.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { createRequire } from 'node:module';
// no package.json here (so the workspace lockfile is untouched): load the built core and its yaml dependency by path
const YAML = createRequire(new URL('../../packages/core/package.json', import.meta.url))('yaml');
const { makeRedactor, DEFAULT_REDACTION } = await import('../../packages/core/dist/index.js');

const src = resolve(process.argv[2] ?? '../OpsDesk');
const here = new URL('.', import.meta.url).pathname;
const SETS = [
  { name: 'mock-v1', match: /_baseline$/, simulated: true, note: 'first rule-based version (keyword retrieval, no rerank)' },
  { name: 'mock-v3', match: /_iter3_mock$/, simulated: true, note: 'current rule-based version' },
  { name: 'real-haiku', match: /_real$/, simulated: false, note: 'claude-haiku-5-5, one trial, run by OpsDesk' },
];
const redact = makeRedactor(DEFAULT_REDACTION);
const dirs = readdirSync(join(src, 'evals/results')).filter((d) => !d.endsWith('retrieval_real'));
const loaded = SETS.map((s) => {
  const dir = dirs
    .filter((d) => s.match.test(d))
    .sort()
    .at(-1);
  if (!dir) throw new Error(`no OpsDesk result directory matches ${s.match}`);
  const rows = readFileSync(join(src, 'evals/results', dir, 'results.jsonl'), 'utf8')
    .split('\n')
    .filter(Boolean)
    .map((l) => JSON.parse(l));
  const summary = JSON.parse(readFileSync(join(src, 'evals/results', dir, 'summary.json'), 'utf8'));
  return { ...s, dir, rows: new Map(rows.map((r) => [r.id, r])), summary };
});
const cases = readdirSync(join(src, 'evals/cases'))
  .filter((f) => f.endsWith('.json'))
  .sort()
  .flatMap((f) => JSON.parse(readFileSync(join(src, 'evals/cases', f), 'utf8')))
  .filter((c) => loaded.every((s) => s.rows.has(c.id)));

const dataset = cases.map((c) => {
  const e = c.expect;
  const answer = {};
  if (e.facts.length) answer.contains = e.facts;
  if (e.forbidden_text.length) answer.not_contains = e.forbidden_text;
  return {
    id: c.id,
    category: c.category,
    input: c.message,
    context: { intent: e.intent, gated: e.gated, escalate: e.escalate, cite_any: e.cite_any },
    expected: {
      ...(e.tools === null ? {} : { tools: e.tools.map((name) => ({ name })), max_extra_calls: 0 }),
      ...(Object.keys(answer).length ? { answer } : {}),
      outcome: 'opsdesk_policy',
    },
  };
});
writeFileSync(
  join(here, 'dataset.yaml'),
  '# Generated by import.mjs from OpsDesk evals/cases\n' + YAML.stringify(dataset, { lineWidth: 0 }),
);

for (const s of loaded) {
  const out = join(here, '.tracegate/runs', s.name);
  mkdirSync(out, { recursive: true });
  const meta = {
    agent: 'opsdesk',
    model: s.simulated ? 'opsdesk-rule-engine' : 'claude-haiku-5-5',
    simulated: s.simulated,
    note: s.note,
    imported_from: `OpsDesk/evals/results/${s.dir}`,
  };
  writeFileSync(
    join(out, 'manifest.json'),
    JSON.stringify({ name: s.name, created: s.summary.created_at, mode: 'record', trials: 1, simulated: s.simulated, meta }, null, 2) +
      '\n',
  );
  for (const c of cases) {
    const r = s.rows.get(c.id);
    let n = 0;
    const ev = (o) => ({ v: 1, run_id: `${s.name}-${c.id}`, id: `e${++n}`, ts: s.summary.created_at, ...o });
    const events = [
      ev({ type: 'run_start', case_id: c.id, trial: 0, input: c.message, meta }),
      // one summary event: OpsDesk reports total tokens, cost and latency per case, not per model call
      ev({
        type: 'model_call',
        step: 0,
        provider: s.simulated ? 'mock' : 'anthropic',
        model: meta.model,
        request: null,
        usage: { input_tokens: r.tokens, output_tokens: 0 },
        cost_usd: r.costUsd,
        latency_ms: r.latencyMs,
      }),
      ...r.actual.tools.map((name) => ev({ type: 'tool_call', step: 0, name, args: null, duration_ms: 0 })),
      ...r.actual.gated.map((name) => ev({ type: 'event', step: 0, name: 'approval_requested', data: { tool: name } })),
      ...(r.actual.escalated ? [ev({ type: 'event', step: 0, name: 'escalation', data: { reasons: r.actual.reasons } })] : []),
      ev({
        type: 'run_end',
        status: 'ok',
        output: r.actual.reply,
        state: {
          intent: r.actual.intent,
          gated: r.actual.gated,
          escalated: r.actual.escalated,
          citations: r.actual.citations,
          opsdesk: { checks: r.checks, pass: r.pass },
        },
        duration_ms: r.latencyMs,
      }),
    ];
    writeFileSync(join(out, `${c.id}__t0.jsonl`), events.map((e) => JSON.stringify(redact(e))).join('\n') + '\n');
  }
  console.log(`${s.name}: ${cases.length} runs from ${s.dir}`);
}
